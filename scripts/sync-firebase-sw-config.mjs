import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const envPath = join(root, ".env.local");
const outPath = join(root, "public", "firebase-messaging-config.js");

function parseEnv(content) {
  const map = new Map();
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const idx = trimmed.indexOf("=");
    if (idx <= 0) continue;
    const key = trimmed.slice(0, idx).trim();
    let value = trimmed.slice(idx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    map.set(key, value);
  }
  return map;
}

const keys = [
  "NEXT_PUBLIC_FIREBASE_API_KEY",
  "NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN",
  "NEXT_PUBLIC_FIREBASE_PROJECT_ID",
  "NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET",
  "NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID",
  "NEXT_PUBLIC_FIREBASE_APP_ID",
];

function envValue(map, key) {
  return map.get(key) || process.env[key] || "";
}

let env = new Map();
if (existsSync(envPath)) {
  env = parseEnv(readFileSync(envPath, "utf8"));
}

const config = {
  apiKey: envValue(env, "NEXT_PUBLIC_FIREBASE_API_KEY"),
  authDomain: envValue(env, "NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN"),
  projectId: envValue(env, "NEXT_PUBLIC_FIREBASE_PROJECT_ID"),
  storageBucket: envValue(env, "NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET"),
  messagingSenderId: envValue(env, "NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID"),
  appId: envValue(env, "NEXT_PUBLIC_FIREBASE_APP_ID"),
};

const body = `// Auto-generated by scripts/sync-firebase-sw-config.mjs — do not edit manually.
self.FIREBASE_MESSAGING_CONFIG = ${JSON.stringify(config, null, 2)};
`;

writeFileSync(outPath, body, "utf8");

const missing = keys.filter((key) => !envValue(env, key));
if (missing.length > 0) {
  console.warn(
    `[sync-firebase-sw-config] Missing in .env.local: ${missing.join(", ")}`,
  );
} else {
  console.log("[sync-firebase-sw-config] Wrote public/firebase-messaging-config.js");
}
